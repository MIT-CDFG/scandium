    /// Blue-noise character (not just any permutation): the mean absolute
    /// difference between toroidally adjacent cells must be well above a
    /// white-noise permutation's clustering floor. For high-frequency
    /// (blue) arrangements of 0..=255 values, adjacent |Δ| averages near
    /// ~100; white noise averages ~85; clustered/smooth arrangements fall
    /// far below. A conservative ≥ 90 bound catches accidental
    /// low-frequency structure without over-pinning the artifact.
    #[test]
    fn bn64_neighbors_differ_like_blue_noise() {
        let mut sum = 0u64;
        let mut n = 0u64;
        for y in 0..64usize {
            for x in 0..64usize {
                let v = BN64[y * 64 + x] as i64;
                let right = BN64[y * 64 + ((x + 1) & 63)] as i64;
                let down = BN64[((y + 1) & 63) * 64 + x] as i64;
                sum += v.abs_diff(right) + v.abs_diff(down);
                n += 2;
            }
        }
        let mean = sum as f64 / n as f64;
        assert!(
            mean >= 90.0,
            "adjacent-cell mean |Δ| {mean:.2} too low for blue noise"
        );
    }

