#   inside it, puts "21" small in the lower right, and carries no element name
#   and no atomic mass at all.

import os
import struct
import sys
import zlib


# ★ HAND-AUTHORED 5x7 GLYPHS. Row strings, "1" is ink. Four characters is
#   the whole alphabet this icon needs, so a bitmap beats a dependency.
GLYPHS = {
    "S": ("01110", "10001", "10000", "01110", "00001", "10001", "01110"),
    "c": ("00000", "00000", "01110", "10001", "10000", "10001", "01110"),
    "2": ("01110", "10001", "00001", "00010", "00100", "01000", "11111"),
    "1": ("00100", "01100", "00100", "00100", "00100", "00100", "01110"),
}


def _stamp(px, size, text, x0, y0, cell, colour):
    """Fill `text`'s glyph cells into px. Pure rectangles, no antialiasing:
    the same honesty the rest of this file has -- what it draws is what it
    computed, with nothing smoothed over."""
    x = x0
    for ch in text:
        rows = GLYPHS[ch]
        for gy, row in enumerate(rows):
            for gx, bit in enumerate(row):
                if bit != "1":
                    continue
                for dy in range(cell):
                    yy = y0 + gy * cell + dy
                    if not (0 <= yy < size):
                        continue
                    for dx in range(cell):
                        xx = x + gx * cell + dx
                        if 0 <= xx < size:
                            px[yy][xx] = colour
        x += (5 + 1) * cell          # one blank column between glyphs


def _stamp_over(px, size, text, x0, y0, cell, ink, ink_on_light,
                rx0, ry0, rx1, ry1):
    """Like _stamp, but a cell that lands inside the rectangle (rx0..rx1,
    ry0..ry1) is drawn in `ink_on_light` instead of `ink`. That is how the
    mark stays legible where it crosses the canvas without an outline, and
    it is one comparison per pixel rather than a compositing pass."""
    x = x0
    for ch in text:
        rows = GLYPHS[ch]
        for gy, row in enumerate(rows):
            for gx, bit in enumerate(row):
                if bit != "1":
                    continue
                for dy in range(cell):
                    yy = y0 + gy * cell + dy
                    if not (0 <= yy < size):
                        continue
                    for dx in range(cell):
                        xx = x + gx * cell + dx
                        if not (0 <= xx < size):
                            continue
                        inside = (rx0 <= xx < rx1) and (ry0 <= yy < ry1)
                        px[yy][xx] = ink_on_light if inside else ink
        x += (5 + 1) * cell


def png_bytes(size: int, scandium: bool = False) -> bytes:
    bg = (0x23, 0x24, 0x28, 255)       # Theme.bgWindow
    surface = (0x37, 0x38, 0x3b, 255)  # Theme.bgRaised
    inner = (0xe2, 0xe4, 0xe7, 255)    # Theme.textPrimary
    corner = size * 18 // 100
    b0, b1 = size * 22 // 100, size * 78 // 100  # raised square
    i0, i1 = size * 38 // 100, size * 62 // 100  # light inner square

    px = []
    for y in range(size):
        line = []
        for x in range(size):
            # Rounded-corner cut for the outer square (quarter-circles).
            dx = min(x, size - 1 - x)
            dy = min(y, size - 1 - y)
            if dx < corner and dy < corner:
                cx, cy = corner - dx, corner - dy
                if cx * cx + cy * cy > corner * corner:
                    line.append((0, 0, 0, 0))
                    continue
            if not scandium and i0 <= x < i1 and i0 <= y < i1:
                line.append(inner)
            elif not scandium and b0 <= x < b1 and b0 <= y < b1:
                line.append(surface)
            else:
                line.append(bg)
        px.append(line)

    if scandium:
        # ⛔⛔ VERSION 2, AND VERSION 1 IS WHY. The first composition drew a
        #   bordered square with "Sc" centred large and "21" small in the corner.
        #   I RENDERED IT AND LOOKED AT IT: that is a periodic-table tile, which
        #   is the one thing WORD 9 forbids -- and my code comment claimed it was
        #   "deliberately NOT a periodic-table tile" while the pixels said
        #   otherwise. A comment asserting a property the artifact does not have
        #   is the failure this desk has spent the day recording.
        #
        #   THE TILE LOOK IS THREE THINGS TOGETHER: an enclosing bordered square,
        #   a large centred symbol, and a small number in a corner. This version
        #   breaks all three. The CANVAS MOTIF is the subject -- a light rectangle
        #   occupying the lower right, which is what this app edits -- and "Sc" is
        #   a mark set over its upper-left corner, overlapping it. There is no
        #   enclosing square, no corner number, no element name, no atomic mass.
        if size >= 32:
            # ONE canvas rectangle, lower-right, and the mark CLEAR OF IT.
            # v2 straddled the two and the "c" was half-swallowed -- legible
            # in my head, not on the screen. Rendered and looked at again.
            c0x, c1x = size * 42 // 100, size * 88 // 100
            c0y, c1y = size * 46 // 100, size * 88 // 100
            for y in range(c0y, c1y):
                for x in range(c0x, c1x):
                    px[y][x] = inner
            cell = max(1, size // 30)
            _stamp(px, size, "Sc", size * 12 // 100, size * 14 // 100, cell, inner)

    rows = []
    for line in px:
        row = bytearray([0])  # filter type 0
        for c in line:
            row += bytes(c)
        rows.append(bytes(row))

    def chunk(tag: bytes, data: bytes) -> bytes:
        return (struct.pack(">I", len(data)) + tag + data
                + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF))

    ihdr = struct.pack(">IIBBBBB", size, size, 8, 6, 0, 0, 0)
    idat = zlib.compress(b"".join(rows), 9)
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", ihdr)
            + chunk(b"IDAT", idat) + chunk(b"IEND", b""))


def main() -> int:
    # The product icon is the DEFAULT (E-02, operator WORD 9). "--scandium" is
    # kept as an accepted no-op so any caller written against the two-mode
    # version keeps working; "--d43-placeholder" reproduces the historical art,
    # which keeps the superseded artifact auditable instead of unreachable.
    flags = {"--scandium", "--d43-placeholder"}
    args = [a for a in sys.argv[1:] if a not in flags]
    scandium = "--d43-placeholder" not in sys.argv[1:]
    if len(args) != 1:
        print("usage: make_placeholder_icon.py <out.iconset> [--d43-placeholder]",
              file=sys.stderr)
        return 2
    outdir = args[0]
    os.makedirs(outdir, exist_ok=True)
    # The iconset roster iconutil expects.
    for base, scale in [(16, 1), (16, 2), (32, 1), (32, 2), (128, 1),
                        (128, 2), (256, 1), (256, 2), (512, 1), (512, 2)]:
        px = base * scale
        name = (f"icon_{base}x{base}.png" if scale == 1
                else f"icon_{base}x{base}@2x.png")
        with open(os.path.join(outdir, name), "wb") as f:
            f.write(png_bytes(px, scandium))
    return 0


if __name__ == "__main__":
    sys.exit(main())
