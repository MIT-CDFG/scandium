# w20_action_record_batch.sh — workflow gate W20 (CP-0.7 subset per plan
# §2.4: actions v1 + headless batch runner just merged; the full spec
# artifact W20-action-record-batch-run.yaml adds the W8 sandboxed-plugin
# step and a Curves adjustment.add — plugin host is a 1.0 row and the
# adjustment compute half is the in-flight O-TOOLS wiring; the brush
# stroke + samples-asset travel legs run in the O-SCRIPT in-crate suite
# (recorded_assets_travel_and_reingest_content_addressed)).
#
# Flow (deterministic fixtures generated by the shipped CLI in WORK):
#   inputs: 6 flat PNGs + 2 .appname docs (one 8-layer carrying a layer
#   named "Grain", one 1-layer)
#   action: appname.action.v1 with 2 command steps — doc.resize
#   (committed params only) and layer.set_props targeting "Grain" by
#   recordedTarget name (§26.1 rule 3) — and NOTHING else (no view/tool
#   steps, §26.1 rule 1; asserted on the file)
#   run:    appname-actions run --on-error continue,
#           template out/{name}-{date:yyyy-MM-dd}.{ext}
#   expect: exit 7; batch-report.json shows the "Grain" step succeeding
#           ONLY on the 8-layer doc and failing everywhere else with
#           error.batch.step_failed naming the unresolved target (§26.2);
#           outputs named per the template with locale-independent date
#           digits; a second run is byte-identical per file
#
# Exit: 0 pass · 1 fail · 2 environment not ready.

set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"

CLI="${APPNAME_CLI:-}"
if [ -z "$CLI" ]; then
    for cand in "$ROOT/target/debug/appname" "$ROOT/target/release/appname"; do
        [ -x "$cand" ] && CLI="$cand" && break
    done
fi
ACT=""
for cand in "$ROOT/target/debug/appname-actions" "$ROOT/target/release/appname-actions"; do
    [ -x "$cand" ] && ACT="$cand" && break
done
[ -n "$CLI" ] || { echo "SKIP: appname-cli not built"; exit 2; }
[ -n "$ACT" ] || { echo "SKIP: appname-actions not built (cargo build -p appname-script --bins)"; exit 2; }

WORK="$(mktemp -d "${TMPDIR:-/tmp}/appname-qa-w20-XXXXXX")"
trap 'rm -rf "$WORK"' EXIT
sha() { shasum -a 256 "$1" | cut -d' ' -f1; }
fail=0

# ---- fixtures ------------------------------------------------------------
IN="$WORK/in"; mkdir -p "$IN"
i=0
for wh in "40 30" "32 32" "64 20" "20 64" "48 48" "56 24"; do
    i=$((i+1))
    set -- $wh
    tmp="$WORK/png$i.appname"
    "$CLI" new --width "$1" --height "$2" --background white --out "$tmp" --json >/dev/null
    "$CLI" export --doc "$tmp" --format png --out "$IN/flat$i.png" --json >/dev/null
done
# 8-layer doc with "Grain" at tree index 3
pkg="$IN/deep.appname"
"$CLI" new --width 40 --height 40 --background white --out "$pkg" --json >/dev/null
for n in 1 2 3 4 5 6 7; do
    name="L$n"; [ "$n" = "3" ] && name="Grain"
    "$CLI" apply --doc "$pkg" --json --command "{\"schema\":\"appname.command.v1\",\"id\":\"20000000-0000-4000-8000-0000000000a$n\",\"kind\":\"layer.add\",\"params\":{\"kind\":\"raster\",\"newLayerId\":\"20000000-0000-4000-8000-0000000000b$n\",\"name\":\"$name\"}}" >/dev/null
done
# 1-layer doc
"$CLI" new --width 40 --height 40 --background white --out "$IN/flat.appname" --json >/dev/null

# ---- the action ----------------------------------------------------------
cat > "$WORK/action.json" <<'EOF'
{
  "schema": "appname.action.v1",
  "name": "w20 grain pass",
  "steps": [
    { "command": { "kind": "doc.resize",
                   "params": { "width": 80, "resample": "bilinear" } } },
    { "command": { "kind": "layer.set_props",
                   "target": { "layerId": "20000000-0000-4000-8000-0000000000b3" },
                   "params": { "opacity": 0.4 } },
      "recordedTarget": { "layerName": "Grain", "treeIndex": 3 } }
  ]
}
EOF
"$ACT" validate --action "$WORK/action.json" >/dev/null \
    && echo "validate PASS (appname.action.v1 accepted)" \
    || { echo "validate FAIL"; fail=1; }
# §26.1 rule 1: exactly 2 command steps, no view/tool/window steps
n="$(python3 -c 'import json;a=json.load(open("'"$WORK"'/action.json"));print(len(a["steps"]), sum(1 for s in a["steps"] if not s["command"]["kind"].split(".")[0] in ("view","window","tool")))')"
[ "$n" = "2 2" ] \
    && echo "steps-clean PASS (2 command steps, zero view/window/tool)" \
    || { echo "steps-clean FAIL ($n)"; fail=1; }

# ---- batch run x2 --------------------------------------------------------
run_batch() { # run_batch <outdir>; returns runner exit
    set +e
    "$ACT" run --action "$WORK/action.json" \
        --in "$IN/flat1.png" --in "$IN/flat2.png" --in "$IN/flat3.png" \
        --in "$IN/flat4.png" --in "$IN/flat5.png" --in "$IN/flat6.png" \
        --in "$IN/deep.appname" --in "$IN/flat.appname" \
        --out "$1/{name}-{date:yyyy-MM-dd}.{ext}" \
        --format png --on-error continue --json > "$1.stdout" 2>&1
    local rc=$?
    set -e
    return $rc
}
rc=0; run_batch "$WORK/out1" || rc=$?
if [ "$rc" = "7" ]; then
    echo "exit-code PASS (7: batch completed with per-file failures)"
else
    echo "exit-code FAIL (got $rc)"; sed -n 1,5p "$WORK/out1.stdout" | sed 's/^/  /'
    fail=1
fi

rep="$WORK/out1/batch-report.json"
if [ -f "$rep" ]; then
    summary="$(python3 - "$rep" <<'EOF'
import json, sys
r = json.load(open(sys.argv[1]))
ok = [x["input"].split("/")[-1] for x in r["results"] if all(s["status"] == "ok" for s in x["steps"])]
bad = {}
for x in r["results"]:
    for s in x["steps"]:
        if s["status"] == "error":
            bad[x["input"].split("/")[-1]] = (x.get("error", {}).get("messageId", "?"),
                                              "Grain" in s.get("detail", ""))
            break
print(r["schema"], r["summary"]["total"], r["summary"]["ok"], r["summary"]["failed"],
      sorted(ok) == ["deep.appname"],
      all(mid == "error.batch.step_failed" and named for mid, named in bad.values()))
EOF
)"
    if [ "$summary" = "appname.batchreport.v1 8 1 7 True True" ]; then
        echo "report PASS (8 files: only deep.appname fully ok; 7 fail at the Grain step, error.batch.step_failed naming the target)"
    else
        echo "report FAIL ($summary)"
        fail=1
    fi
else
    echo "report FAIL (no batch-report.json)"
    fail=1
fi

# template naming: ICU-stable ASCII date digits regardless of locale env
d="$(date -u +%Y-%m-%d)"
if ls "$WORK/out1/deep-$d.png" >/dev/null 2>&1; then
    echo "template PASS (deep-$d.png per {name}-{date:yyyy-MM-dd}.{ext})"
else
    echo "template FAIL (out1: $(ls "$WORK/out1" 2>/dev/null | tr '\n' ' '))"
    fail=1
fi

rc=0; LC_ALL=ja_JP.UTF-8 run_batch "$WORK/out2" || rc=$?
if cmp -s "$WORK/out1/deep-$d.png" "$WORK/out2/deep-$d.png"; then
    echo "determinism PASS (second run byte-identical, ja_JP locale env, same ASCII digits)"
else
    echo "determinism FAIL"
    fail=1
fi

if [ "$fail" -ne 0 ]; then
    echo "W20 action-record-batch: FAIL"
    exit 1
fi
echo "W20 action-record-batch: PASS"
