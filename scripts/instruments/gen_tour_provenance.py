"""Regenerate artifacts/tour-chrome.PROVENANCE.md (H-06: a provenance line per image).

DERIVED, never hand-written — operator's WORD 4 (3), 2026-09-11: "derive it (adapt
qa/q-tutorial's gen_provenance.py), never type it."  Adapted from that script, which
exists because three of four byte counts typed by hand were wrong.

The producer of each frame is read FROM THE SHELL SOURCE, not from a list kept here:
`capture(window, dir, QStringLiteral("NN-name.png"), ...)` in shell/src/tour.cpp is the
window-grab door.  A committed image whose name appears in no such call, and in no other
.png literal in that file, is reported UNATTRIBUTED rather than guessed at.

  usage: python3 scripts/instruments/gen_tour_provenance.py > artifacts/tour-chrome.PROVENANCE.md

  The output lives BESIDE the goldens directory, not inside it -- operator WORD 5,
  2026-09-12, ruling Q-D56 (b): a document inside artifacts/tour-chrome/ is a
  non-.png member of a directory the gate diffs whole, which redded main's tour arm.
  Beside-the-directory is the stronger invariant; the guard keeps its document
  exclusion as a belt.
"""
import glob, hashlib, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, f'{ROOT}/reports/aud-parity-harness')
from png import read_png

TOUR_SRC = f'{ROOT}/shell/src/tour.cpp'
IMG_DIR  = f'{ROOT}/artifacts/tour-chrome'


def producers():
    """(grab_names, other_png_literals) read from the shell's own tour source."""
    src = open(TOUR_SRC, encoding='utf-8', errors='replace').read()
    grabs = set(re.findall(
        r'capture\s*\([^;]*?QStringLiteral\(\s*"([^"]+\.png)"', src, re.S))
    every = set(re.findall(r'"([A-Za-z0-9_.-]+\.png)"', src))
    return grabs, every - grabs


def main():
    grabs, others = producers()
    if not grabs:
        sys.exit('gen_tour_provenance: NO capture() names found in tour.cpp -- '
                 'the extraction is broken, not the tour. Refusing to emit.')
    out = []
    w = out.append
    # REUSE-IgnoreStart
    # The two lines below are the header this script WRITES into its output; they
    # are not this file's own licence. Without the fence, `reuse lint` parses the
    # emitted string as an expression ("GPL-3.0-only -->") and reports it invalid --
    # which is exactly what it did when this generator first landed (entry 865),
    # taking the repo from 19 invalid expressions to 20. gate.sh:5/:1170 uses the
    # same fence for the same reason.
    w("<!-- SPDX-License-Identifier: GPL-3.0-only -->")
    w("<!-- Copyright (c) 2026 the Appname contributors -->\n")
    # REUSE-IgnoreEnd
    w("# Image provenance — `artifacts/tour-chrome/`\n")
    w("**H-06: a provenance line per image.** GENERATED by")
    w("`scripts/instruments/gen_tour_provenance.py` from `shell/src/tour.cpp` and the committed")
    w("files themselves — **never typed** (operator's WORD 4 (3), 2026-09-11). Every producer below")
    w("is read from the shell source at generation time; this file keeps no list of its own.\n")
    w("**Q-D48 (a) / Q-D50 (a):** every image here is produced by a **tracked generator** —")
    w("`shell/src/tour.cpp`, the shell's own recovery tour, via `QQuickWindow::grabWindow()`.")
    w("**No third-party asset contributes a pixel to any of them**, and no Adobe or other")
    w("competitor's pixel, glyph, page imagery or trade dress appears in the product or here.\n")
    w("These frames are **re-pinned** by the operator's word under the `89ac27f6` protocol; each")
    w("re-pin regenerates this file. The counts below are derived at generation time and are not")
    w("predicates — §10.5 / AMENDMENT 8 clause (c).\n")
    w("| image | bytes | px | sha256 | produced by |")
    w("|---|---|---|---|---|")
    n = una = 0
    sha_index = []
    for path in sorted(glob.glob(f'{IMG_DIR}/*.png')):
        base = os.path.basename(path)
        blob = open(path, 'rb').read()
        sha_index.append((hashlib.sha256(blob).hexdigest(), base))
        iw, ih, _ = read_png(path)
        if base in grabs:
            prod = '`tour.cpp` `capture()` — window grab'
        elif base in others:
            prod = f'`tour.cpp`, not via `capture()` — see the source for `{base}`'
        else:
            prod = '**UNATTRIBUTED**'
            una += 1
        n += 1
        w(f"| `{base}` | {len(blob)} | {iw}×{ih} | `{hashlib.sha256(blob).hexdigest()[:16]}` | {prod} |")
    # ⛔ THE COUNTS CAN AGREE WHILE THE SETS DIFFER. On the first run this file
    # reported "32 declares / 32 images / 0 unattributed" while one declared frame
    # was absent and one present image was not a capture() frame -- the totals
    # matched by coincidence and read as correspondence. Report the SETS.
    present = {os.path.basename(f) for f in glob.glob(f'{IMG_DIR}/*.png')}
    declared_absent = sorted(grabs - present)
    # ⛔ PRESENCE, AGREEMENT AND DISTINCTNESS ARE THREE QUESTIONS (O-WATCH #680:
    # 35 goldens carried 35 present hashes that all agreed, and were only 31
    # DISTINCT files). This file answered "what produced it" and never "is it
    # its own image". For a tour of WINDOW GRABS the question has teeth: two
    # consecutive steps that leave the window unchanged produce byte-identical
    # frames, and a frame identical to its neighbour evidences nothing about
    # its own step. Measured at generation, not assumed.
    dupes = {}
    for h, b in sha_index:
        dupes.setdefault(h, []).append(b)
    dupes = {h: v for h, v in dupes.items() if len(v) > 1}
    w(f"\n**{n} images, {una} unattributed.** `tour.cpp` declares **{len(grabs)}** `capture()` frames")
    w(f"and **{len(others)}** other `.png` literal(s).")
    if declared_absent:
        w("")
        w(f"⛔ **DECLARED BY `capture()` AND NOT COMMITTED HERE ({len(declared_absent)}):** "
          + ", ".join(f"`{d}`" for d in declared_absent) + ".")
        w("*Not necessarily a defect — a captured frame may be consumed and committed by another")
        w("lane under another name. It is reported because the totals above can agree while the")
        w("sets differ, and a coincidental match reads as correspondence.*")
    w("")
    w("")
    if dupes:
        w(f"⛔ **NOT DISTINCT ({len(dupes)} hash(es) shared):** " + " · ".join(
            "`" + "`, `".join(v) + "`" for v in dupes.values()) + ".")
        w("*A window grab identical to another evidences nothing about its own step.*")
    else:
        w(f"**{len(sha_index)} images, {len({h for h, _ in sha_index})} distinct** — no two frames share bytes.")
    w("")
    w("A committed image with no line here, a line naming an image that no longer exists, any")
    w("line reading UNATTRIBUTED, or two frames sharing a hash, is a finding.")
    print('\n'.join(out))


if __name__ == '__main__':
    main()
