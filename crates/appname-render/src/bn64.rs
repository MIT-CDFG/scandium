    /// The one-time generator, verbatim — provenance pin for the committed
    /// constant (module doc). Void-and-cluster per Ulichney's published
    /// algorithm; deterministic by construction (integer distances,
    /// literal-based weights, IEEE-exact ops, lowest-index tie breaks).
    mod gen {
        const N: usize = 64;
        const CELLS: usize = N * N;
        /// Gaussian-shaped filter base: w(d²) = R^(d²), R ≈ exp(-1/(2σ²)),
        /// σ = 1.5. A source literal so every platform computes identical
        /// f64 weights.
        const R: f64 = 0.8007374029168081;

        fn wrap_delta(a: usize, b: usize) -> usize {
            let d = a.abs_diff(b);
            d.min(N - d)
        }

        /// w = R^(d²) by binary exponentiation — fixed operation order.
        fn weight(d2: usize) -> f64 {
            let mut result = 1.0f64;
            let mut base = R;
            let mut e = d2;
            while e > 0 {
                if e & 1 == 1 {
                    result *= base;
                }
                base *= base;
                e >>= 1;
            }
            result
        }

        struct Field {
            energy: Vec<f64>,
            w: Vec<f64>, // w[dy * N + dx] for wrapped deltas
        }

        impl Field {
            fn new() -> Field {
                let mut w = vec![0.0f64; CELLS];
                for dy in 0..N {
                    for dx in 0..N {
                        let ddx = dx.min(N - dx);
                        let ddy = dy.min(N - dy);
                        w[dy * N + dx] = weight(ddx * ddx + ddy * ddy);
                    }
                }
                Field {
                    energy: vec![0.0f64; CELLS],
                    w,
                }
            }

            fn apply(&mut self, p: usize, sign: f64) {
                let (px, py) = (p % N, p / N);
                for y in 0..N {
                    let dy = wrap_delta(y, py);
                    let row = y * N;
                    for x in 0..N {
                        let dx = wrap_delta(x, px);
                        self.energy[row + x] += sign * self.w[dy * N + dx];
                    }
                }
            }

            /// Max-energy cell in state `want`; ties → lowest index.
            fn argmax(&self, pattern: &[bool], want: bool) -> usize {
                let mut best = usize::MAX;
                let mut best_e = f64::NEG_INFINITY;
                for (i, &p) in pattern.iter().enumerate().take(CELLS) {
                    if p == want && self.energy[i] > best_e {
                        best_e = self.energy[i];
                        best = i;
                    }
                }
                best
            }

            /// Min-energy cell in state `want`; ties → lowest index.
            fn argmin(&self, pattern: &[bool], want: bool) -> usize {
                let mut best = usize::MAX;
                let mut best_e = f64::INFINITY;
                for (i, &p) in pattern.iter().enumerate().take(CELLS) {
                    if p == want && self.energy[i] < best_e {
                        best_e = self.energy[i];
                        best = i;
                    }
                }
                best
            }
        }

        fn splitmix64(state: &mut u64) -> u64 {
            *state = state.wrapping_add(0x9E3779B97F4A7C15);
            let mut z = *state;
            z = (z ^ (z >> 30)).wrapping_mul(0xBF58476D1CE4E5B9);
            z = (z ^ (z >> 27)).wrapping_mul(0x94D049BB133111EB);
            z ^ (z >> 31)
        }

        pub fn generate() -> [u8; CELLS] {
            let ones0 = CELLS / 10; // 409 initial minority points

            // Deterministic initial pattern: Fisher-Yates over 0..CELLS,
            // take the first `ones0` cells. Seed spells "BN64".
            let mut idx: Vec<usize> = (0..CELLS).collect();
            let mut rng = 0x424E3634u64;
            for i in (1..CELLS).rev() {
                let j = (splitmix64(&mut rng) % (i as u64 + 1)) as usize;
                idx.swap(i, j);
            }
            let mut pattern = vec![false; CELLS];
            let mut field = Field::new();
            for &p in &idx[..ones0] {
                pattern[p] = true;
                field.apply(p, 1.0);
            }

            // Phase 0 — relax the prototype: move the tightest cluster's
            // point into the largest void until they coincide (Ulichney's
            // termination).
            loop {
                let c = field.argmax(&pattern, true);
                pattern[c] = false;
                field.apply(c, -1.0);
                let v = field.argmin(&pattern, false);
                pattern[v] = true;
                field.apply(v, 1.0);
                if v == c {
                    break;
                }
            }
            let prototype = pattern.clone();

            let mut rank = vec![0usize; CELLS];

            // Phase 1 — rank the prototype's points ones0−1 … 0 by
            // successive tightest-cluster removal.
            {
                let mut pat = prototype.clone();
                let mut f = Field::new();
                for (i, &p) in pat.iter().enumerate().take(CELLS) {
                    if p {
                        f.apply(i, 1.0);
                    }
                }
                for r in (0..ones0).rev() {
                    let c = f.argmax(&pat, true);
                    pat[c] = false;
                    f.apply(c, -1.0);
                    rank[c] = r;
                }
            }

            // Phase 2 — grow from the prototype: insert into the largest
            // void, ranks ones0 … CELLS/2 − 1.
            let mut pat = prototype;
            let mut f = Field::new();
            for (i, &p) in pat.iter().enumerate().take(CELLS) {
                if p {
                    f.apply(i, 1.0);
                }
            }
            for r in ones0..CELLS / 2 {
                let v = f.argmin(&pat, false);
                pat[v] = true;
                f.apply(v, 1.0);
                rank[v] = r;
            }

            // Phase 3 — ones are now the majority: track the ZERO
            // pattern's energy and convert its tightest cluster, ranks
            // CELLS/2 … CELLS−1.
            let mut zf = Field::new();
            for (i, &p) in pat.iter().enumerate().take(CELLS) {
                if !p {
                    zf.apply(i, 1.0);
                }
            }
            for r in CELLS / 2..CELLS {
                let c = zf.argmax(&pat, false);
                pat[c] = true;
                zf.apply(c, -1.0);
                rank[c] = r;
            }

            // rank is a permutation of 0..CELLS; store rank >> 4 so each
            // u8 value appears exactly 16 times (§4.5 threshold domain).
            let mut out = [0u8; CELLS];
            for i in 0..CELLS {
                out[i] = (rank[i] >> 4) as u8;
            }
            out
        }
    }

