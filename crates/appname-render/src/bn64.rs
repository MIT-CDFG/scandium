/// Per-layer dissolve offsets (§4.5 seed rule): `blake3(doc_uuid_bytes ||
/// layer_uuid_bytes)`, `ox = seed[0] & 63`, `oy = seed[1] & 63` —
/// layer-decorrelated, document-stable, replay-stable.
pub fn bn_offsets(doc: DocumentId, layer: LayerId) -> (i32, i32) {
    let h = ContentHash::from_stream(|hasher| {
        hasher.update(doc.as_uuid().as_bytes());
        hasher.update(layer.as_uuid().as_bytes());
    });
    let seed = h.as_bytes();
    ((seed[0] & 63) as i32, (seed[1] & 63) as i32)
}

/// The §4.5 threshold value for **document-space** pixel `(px, py)` under
/// per-layer offsets `(ox, oy)`:
/// `n = (f32(BN64[((py+oy)&63)·64 + ((px+ox)&63)]) + 0.5) / 256`.
///
/// `& 63` on `i32` is the WGSL kernel's own indexing expression
/// (`(p_doc + u.bn_off) & vec2<i32>(63, 63)`) and is a correct toroidal
/// wrap for negative coordinates too (two's-complement AND with a
/// power-of-two mask ≡ `rem_euclid(64)`), so off-canvas content (§2.5)
/// dissolves seamlessly.
#[inline]
pub fn bn_threshold(px: i32, py: i32, off: (i32, i32)) -> f32 {
    let x = ((px + off.0) & 63) as usize;
    let y = ((py + off.1) & 63) as usize;
    (BN64[y * 64 + x] as f32 + 0.5) / 256.0
}

