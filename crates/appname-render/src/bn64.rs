    /// Threshold rule mechanics: value lookup matches the formula, and
    /// negative document coordinates wrap toroidally (`& 63` ≡
    /// `rem_euclid(64)`).
    #[test]
    fn bn_threshold_formula_and_negative_wrap() {
        // Direct formula spot-check at (0,0)/(0,0): first committed byte.
        let want = (BN64[0] as f32 + 0.5) / 256.0;
        assert_eq!(bn_threshold(0, 0, (0, 0)), want);
        // Offsets shift lookup: (px+ox)&63, (py+oy)&63.
        assert_eq!(
            bn_threshold(3, 2, (5, 1)),
            (BN64[3 * 64 + 8] as f32 + 0.5) / 256.0
        );
        // Negative coordinates wrap: -1 & 63 == 63.
        assert_eq!(
            bn_threshold(-1, -1, (0, 0)),
            (BN64[63 * 64 + 63] as f32 + 0.5) / 256.0
        );
        for (px, py) in [(-1, -130), (-64, 5), (i32::MIN + 64, i32::MAX - 63)] {
            let via_mask = bn_threshold(px, py, (0, 0));
            let x = (px.rem_euclid(64)) as usize;
            let y = (py.rem_euclid(64)) as usize;
            assert_eq!(via_mask, (BN64[y * 64 + x] as f32 + 0.5) / 256.0);
        }
        // Domain bounds: α_eff = 1 always passes, α_eff = 0 never does.
        let (lo, hi) = ((0.0 + 0.5) / 256.0, (255.0 + 0.5) / 256.0);
        for v in BN64.iter() {
            let n = (*v as f32 + 0.5) / 256.0;
            assert!((lo..=hi).contains(&n));
        }
    }
