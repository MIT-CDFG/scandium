/// Number of 5 nm samples over 360..830 nm.
pub const CIE_SAMPLES: usize = 95;
/// Lowest tabulated wavelength (nm).
pub const CIE_LAMBDA_MIN: f64 = 360.0;
/// Highest tabulated wavelength (nm).
pub const CIE_LAMBDA_MAX: f64 = 830.0;

/// Linear interpolation into a CIE table at wavelength `x` nm (port of
/// `cie_interp`).
pub fn cie_interp(data: &[f64; CIE_SAMPLES], x: f64) -> f64 {
    let mut x = x - CIE_LAMBDA_MIN;
    x *= (CIE_SAMPLES - 1) as f64 / (CIE_LAMBDA_MAX - CIE_LAMBDA_MIN);
    let offset = (x as isize).clamp(0, CIE_SAMPLES as isize - 2) as usize;
    let weight = x - offset as f64;
    (1.0 - weight) * data[offset] + weight * data[offset + 1]
}

